import test from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import {appHarness} from './app-harness.mjs';

const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1sAAAAASUVORK5CYII=','base64');

test('admin sees media counts, edits a listing, uploads a photo, adds a YouTube link and publishes',async t=>{
  const h=await appHarness();t.after(h.close);
  const browser=await chromium.launch({headless:true});t.after(()=>browser.close());
  const context=await browser.newContext({extraHTTPHeaders:{'oai-authenticated-user-id':'test-admin','oai-authenticated-user-email':'admin@example.test'}});
  const page=await context.newPage();
  await page.goto(h.url+'/admin');
  const counts=page.getByLabel('Media for Centurion Park · 1 Bedroom',{exact:true});
  await counts.getByText('Cover photo only',{exact:true}).waitFor();
  await counts.getByText('No video',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Edit Centurion Park · 1 Bedroom',exact:true}).click();
  await page.getByRole('heading',{name:'Edit Centurion Park · 1 Bedroom',exact:true}).waitFor();
  assert.equal(await page.getByLabel('Rent (THB / month)',{exact:true}).inputValue(),'25000');
  await page.getByLabel('Rent (THB / month)',{exact:true}).fill('26000');
  for(const label of ['District','University','Development project']) assert.equal(await page.getByRole('combobox',{name:label,exact:true}).count(),1);
  assert.equal(await page.getByRole('group',{name:'Project Features',exact:true}).count(),1);
  await page.getByLabel('District',{exact:true}).fill('New neighbourhood');
  await page.getByLabel('University',{exact:true}).fill('New campus');
  await page.getByLabel('Development project',{exact:true}).fill('New project');
  await page.locator('.editor-drop input[type=file]').first().setInputFiles({name:'bedroom.png',mimeType:'image/png',buffer:png});
  await page.getByText('1 file uploaded. Save the listing to publish it.',{exact:true}).waitFor();
  await page.getByLabel('Caption',{exact:true}).fill('Bedroom');
  await page.getByRole('button',{name:'YouTube link',exact:true}).click();
  await page.getByLabel('YouTube link',{exact:true}).fill('https://www.youtube.com/shorts/dQw4w9WgXcQ');
  await page.locator('iframe[title="Video preview"]').waitFor();
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await page.getByText('Listing saved.').waitFor();
  await counts.getByText('1 photo',{exact:true}).waitFor();
  await counts.getByText('YouTube video',{exact:true}).waitFor();
  await page.getByRole('heading',{name:'Add listing',exact:true}).waitFor();
  await page.getByRole('button',{name:'Edit Centurion Park · 1 Bedroom',exact:true}).click();
  await page.getByRole('heading',{name:'Edit Centurion Park · 1 Bedroom',exact:true}).waitFor();
  assert.equal(await page.getByLabel('University',{exact:true}).inputValue(),'New campus');
  assert.equal(await page.getByLabel('Development project',{exact:true}).inputValue(),'New project');
  for(const [field,value] of [['district','New neighbourhood'],['university','New campus'],['developmentProject','New project']]) assert.equal(await page.locator(`#listing-${field}-options option[value="${value}"]`).count(),1,'saved names become suggestions');
  const live=await (await context.request.get(h.url+'/residences/centurion-park-ari-soi-5-1br')).text();
  assert.match(live,/฿26,000/);
  assert.match(live,/Bedroom · Owner-supplied/);
  assert.match(live,/<dt>University/);
  assert.match(live,/New campus/);
  assert.match(live,/New project/);
  assert.match(live,/New neighbourhood/);
  assert.match(live,/youtube-nocookie\.com\/embed\/dQw4w9WgXcQ/);
  const detailPage=await context.newPage();
  await detailPage.setViewportSize({width:390,height:844});
  await detailPage.goto(h.url+'/residences/centurion-park-ari-soi-5-1br');
  await detailPage.locator('.residence-location-facts').screenshot({path:'/private/tmp/listing-detail-facts-390.png'});
  await detailPage.getByRole('link',{name:'New neighbourhood',exact:true}).click();
  await detailPage.waitForURL('**/areas/new-neighbourhood-*');
  await detailPage.getByRole('heading',{name:'New neighbourhood',exact:true,level:1}).waitFor();
  assert.equal(await detailPage.locator('.collection .property-card').count(),1);
  await detailPage.close();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile admin has no horizontal overflow');
  await page.locator('.admin-list').screenshot({path:'/private/tmp/listing-admin-390.png'});
  const remove=page.getByRole('button',{name:'Delete Centurion Park · 1 Bedroom',exact:true});
  page.once('dialog',dialog=>dialog.dismiss());
  await remove.click();
  assert.equal(await remove.count(),1,'cancel keeps the listing');
  page.once('dialog',dialog=>dialog.accept());
  await remove.click();
  await page.getByText('Listing deleted.',{exact:true}).waitFor();
  await page.getByRole('heading',{name:'Add listing',exact:true}).waitFor();
  await page.reload();
  assert.equal(await page.getByRole('button',{name:'Edit Centurion Park · 1 Bedroom',exact:true}).count(),0);
  assert.equal((await context.request.get(h.url+'/residences/centurion-park-ari-soi-5-1br')).status(),404);

});
