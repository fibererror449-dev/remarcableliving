// Lists the property and neighbourhood media that actually exists under public/
// so pages can skip references to files that were never committed.
// Run by the prebuild/predev hooks; the output is committed.
import { readdirSync, statSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const publicDir = join(root, "public");
const roots = ["properties", "bangkok"];

function walk(dir, out) {
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith(".")) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push("/" + relative(publicDir, full).split("\\").join("/"));
  }
  return out;
}

export function collectMedia() {
  return roots.flatMap((name) => existsSync(join(publicDir, name)) ? walk(join(publicDir, name), []) : []).sort();
}

const files = collectMedia();
const source = `// Generated by scripts/generate-media-manifest.mjs. Do not edit.\n// Media present under public/ at build time (${files.length} files).\nexport const mediaFiles: ReadonlySet<string> = new Set<string>([\n${files.map((file) => `  ${JSON.stringify(file)},`).join("\n")}\n]);\n`;
const target = join(root, "lib", "media-manifest.generated.ts");
if (!existsSync(target) || readFileSync(target, "utf8") !== source) {
  writeFileSync(target, source);
  console.log(`media manifest: ${files.length} files written to lib/media-manifest.generated.ts`);
}
